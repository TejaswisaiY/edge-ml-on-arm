"""Turn raw benchmark JSON into ``results/SUMMARY.md``.

Every number in the summary is copied from a JSON file produced by a CI run, and each
machine section links to that run, so any figure can be traced back to its log.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from . import paths


def _fmt_pct(x: float | None) -> str:
    return "-" if x is None else f"{100 * x:.2f}%"


def machine_section(name: str, bench: dict) -> list[str]:
    s = bench["system"]
    feats = ", ".join(f for f, on in s["ml_cpu_features"].items() if on) or "none detected"
    lines = [f"## {name}", ""]
    lines.append(f"- CPU: **{s['cpu_model']}** ({s['machine']}, {s['logical_cpus']} logical CPUs)")
    lines.append(f"- ML-relevant CPU features: {feats}")
    lines.append(f"- Software: Python {s['python']}, PyTorch {s['torch']}, ExecuTorch {s['executorch']}")
    if s.get("ci"):
        lines.append(f"- Source run: {s['ci']['run_url']} (commit `{(s['ci'].get('commit') or '')[:7]}`)")
    lines += ["", "| Model | Runtime | Precision | Threads | Median latency (ms) | p90 (ms) | File size (MB) "
                  "| RAM added (MiB) | In-scope accuracy | OOS recall |",
              "|---|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for r in bench["results"]:
        t = r.get("test") or {}
        size = f"{r['pte_bytes'] / 1e6:.2f}" if r.get("pte_bytes") else "-"
        mem = f"{r['memory']['delta_mib']:.1f}" if r.get("memory") else "-"
        runtime = "PyTorch eager" if r["backend"] == "pytorch_eager" else "ExecuTorch + XNNPACK"
        lines.append(f"| {r['preset']} | {runtime} | {r['precision']} | {r['threads']} | "
                     f"{r['latency']['median_ms']:.3f} | {r['latency']['p90_ms']:.3f} | {size} | {mem} | "
                     f"{_fmt_pct(t.get('in_scope_accuracy'))} | {_fmt_pct(t.get('oos_recall'))} |")
    return lines + [""]


def build(results_dir: Path) -> str:
    lines = ["# Results", "",
             "Generated by `python -m edgeml.report` from the JSON files in this folder. "
             "Do not edit by hand.", ""]
    training = sorted((results_dir / "training").glob("*/metrics.json"))
    if training:
        lines += ["## Training (test split, PyTorch model)", "",
                  "| Model | Parameters | Best epoch (chosen on validation) | In-scope accuracy | OOS recall |",
                  "|---|---:|---:|---:|---:|"]
        for p in training:
            m = json.loads(p.read_text())
            c = json.loads((p.parent / "config.json").read_text())
            lines.append(f"| {m['preset']} | {c['parameters']['total']:,} | {m['best_epoch']} | "
                         f"{_fmt_pct(m['test']['in_scope_accuracy'])} | {_fmt_pct(m['test']['oos_recall'])} |")
        lines.append("")
    for bench_path in sorted(results_dir.glob("*/benchmark.json")):
        lines += machine_section(bench_path.parent.name, json.loads(bench_path.read_text()))
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", type=Path, default=paths.RESULTS)
    a = ap.parse_args(argv)
    out = a.results / "SUMMARY.md"
    out.write_text(build(a.results))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
